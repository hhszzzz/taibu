#!/usr/bin/env node
// Generates database/schema.sql, the reviewed snapshot of the schema produced
// by applying every migration. The file is documentation plus a CI drift gate:
// `pnpm db:schema:check` fails when the applied migrations and the committed
// snapshot disagree.
//
// Usage:
//   SCHEMA_SOURCE_URL=postgres://... pnpm db:schema
//   SCHEMA_SOURCE_URL=postgres://... pnpm db:schema:check
//
// The source database must be fully migrated. pg_dump 17 is required.
import { spawn } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { normalizeSchemaDump } from './normalize-schema.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const PG_DUMP_BIN = process.env.PG_DUMP_BIN || 'pg_dump';
const args = process.argv.slice(2);
const has = (flag) => args.includes(flag);
const value = (flag, fallback) => {
  const index = args.indexOf(flag);
  return index === -1 ? fallback : args[index + 1];
};

const dsn = value('--source', process.env.SCHEMA_SOURCE_URL || process.env.MIGRATOR_DATABASE_URL);
const outputPath = path.resolve(value('--output', path.join(root, 'database/schema.sql')));
const check = has('--check');

if (!dsn) {
  console.error('[db:schema] SCHEMA_SOURCE_URL (or MIGRATOR_DATABASE_URL, or --source) is required');
  process.exit(1);
}

function connectionEnv(url) {
  const parsed = new URL(url);
  return {
    ...process.env,
    PGHOST: decodeURIComponent(parsed.hostname),
    PGPORT: parsed.port || '5432',
    PGUSER: decodeURIComponent(parsed.username),
    PGPASSWORD: decodeURIComponent(parsed.password),
    PGDATABASE: decodeURIComponent(parsed.pathname.slice(1)),
    PGOPTIONS: '',
  };
}

function dumpSchema() {
  return new Promise((resolve, reject) => {
    const child = spawn(PG_DUMP_BIN, [
      '--schema-only',
      '--schema=public',
      '--schema=identity',
      '--schema=auth',
      '--schema=taibu_meta',
      '--no-owner',
      '--no-privileges',
      '--no-comments',
    ], { env: connectionEnv(dsn), stdio: ['ignore', 'pipe', 'pipe'] });
    let stdout = '';
    let stderr = '';
    child.stdout.on('data', (chunk) => { stdout += chunk; });
    child.stderr.on('data', (chunk) => { stderr += chunk; });
    child.on('error', reject);
    child.on('close', (code) => {
      if (code === 0) resolve(stdout);
      else reject(new Error(`pg_dump failed (${code}): ${stderr.trim().split('\n').slice(-3).join(' | ')}`));
    });
  });
}

const HEADER = `-- Database schema snapshot.
-- Generated by scripts/db/dump-schema.mjs from a database with every migration
-- applied. Do not edit by hand: run \`pnpm db:schema\` and commit the result.
--

`;

const normalized = HEADER + normalizeSchemaDump(await dumpSchema());

if (check) {
  if (!existsSync(outputPath)) {
    console.error(`[db:schema] snapshot missing: ${outputPath}`);
    process.exitCode = 1;
  } else if (readFileSync(outputPath, 'utf8') !== normalized) {
    console.error('[db:schema] database/schema.sql is out of date; run `pnpm db:schema`');
    process.exitCode = 1;
  } else {
    console.log('[db:schema] snapshot is up to date');
  }
} else {
  mkdirSync(path.dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, normalized);
  console.log(`[db:schema] wrote ${outputPath}`);
}
